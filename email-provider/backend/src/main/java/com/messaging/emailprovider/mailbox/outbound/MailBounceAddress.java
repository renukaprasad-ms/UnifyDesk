package com.messaging.emailprovider.mailbox.outbound;

import com.messaging.emailprovider.common.exception.BadRequestException;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.MessageDigest;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.autoconfigure.condition.ConditionalOnExpression;
import org.springframework.stereotype.Component;

/**
 * Signed VERP return-path for a single recipient of a single mailbox intent.
 * The SMTP envelope sender is NOT the visible From header.
 *
 * Accept only bounce addresses generated by our MTA, checked against both the
 * configured bounce domain and an HMAC. No mail body/header IDs are trusted.
 */
@Component
@ConditionalOnExpression("${app.mail.outbound.enabled:false} || ${app.mail.feedback.enabled:false}")
public class MailBounceAddress {
  private static final Pattern LOCAL = Pattern.compile(
      "^ud\\+([1-9][0-9]{0,18})\\.([1-9][0-9]{0,18})\\.([0-9a-f]{16})$");
  private final String domain;
  private final byte[] secret;

  public record Target(long intentId,long recipientId) {}

  public MailBounceAddress(
      @Value("${app.mail.bounce.domain:}") String domain,
      @Value("${app.mail.bounce.hmac-secret:}") String secret) {
    this.domain=domain==null?"":domain.toLowerCase(Locale.ROOT);
    if (!this.domain.matches("[a-z0-9-]+(\\.[a-z0-9-]+)+")
        || this.domain.length()>180 || this.domain.contains("..")
        || secret==null || secret.getBytes(StandardCharsets.UTF_8).length<32) {
      throw new IllegalStateException("Mail bounce domain and >=32-byte HMAC secret required");
    }
    this.secret=secret.getBytes(StandardCharsets.UTF_8);
  }

  public String envelopeFrom(long intentId,long recipientId) {
    if(intentId<=0 || recipientId<=0) throw new IllegalArgumentException("Invalid bounce target");
    return "ud+"+intentId+"."+recipientId+"."+tag(intentId,recipientId)+"@"+domain;
  }

  public Target verify(String bounceRecipient) {
    if(bounceRecipient==null || bounceRecipient.length()>254
        || bounceRecipient.indexOf('@')!=bounceRecipient.lastIndexOf('@')) {
      throw new BadRequestException("Invalid mailbox bounce recipient");
    }
    int at=bounceRecipient.indexOf('@');
    if(at<=0 || !bounceRecipient.substring(at+1).equalsIgnoreCase(domain)) {
      throw new BadRequestException("Unknown mailbox bounce domain");
    }
    Matcher matcher=LOCAL.matcher(bounceRecipient.substring(0,at).toLowerCase(Locale.ROOT));
    if(!matcher.matches()) throw new BadRequestException("Malformed mailbox bounce token");
    try {
      long intentId=Long.parseLong(matcher.group(1));
      long recipientId=Long.parseLong(matcher.group(2));
      byte[] provided=HexFormat.of().parseHex(matcher.group(3));
      byte[] expected=HexFormat.of().parseHex(tag(intentId,recipientId));
      if(!MessageDigest.isEqual(provided,expected)) {
        throw new BadRequestException("Invalid mailbox bounce signature");
      }
      return new Target(intentId,recipientId);
    } catch(NumberFormatException invalid) {
      throw new BadRequestException("Invalid mailbox bounce identifier");
    }
  }

  private String tag(long intentId,long recipientId) {
    try {
      Mac mac=Mac.getInstance("HmacSHA256");
      mac.init(new SecretKeySpec(secret,"HmacSHA256"));
      byte[] digest=mac.doFinal((intentId+"."+recipientId)
          .getBytes(StandardCharsets.US_ASCII));
      return HexFormat.of().formatHex(Arrays.copyOf(digest,8));
    } catch(GeneralSecurityException failure) {
      throw new IllegalStateException("HMAC-SHA256 unavailable",failure);
    }
  }
}
