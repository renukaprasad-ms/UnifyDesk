-- Billing V2 R2: explicit association between independent UnifyDesk Mail projects
-- and platform companies. Mail project IDs are NOT platform company IDs.
-- REPORT_ONLY prevents a second financial charge in central Billing V2.
create table billing_mail_project_links (
  id bigint generated by default as identity primary key,
  company_id bigint not null references companies(id) on delete restrict,
  mail_project_id bigint not null unique check (mail_project_id > 0),
  mode varchar(32) not null default 'REPORT_ONLY'
    check (mode = 'REPORT_ONLY'),
  state varchar(16) not null default 'ACTIVE'
    check (state in ('ACTIVE','PAUSED')),
  ownership_proof varchar(500) not null,
  effective_from timestamptz not null,
  last_external_usage_id bigint not null default 0
    check (last_external_usage_id >= 0),
  last_synced_at timestamptz,
  created_by_user_id bigint not null references users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index idx_billing_mail_link_company on billing_mail_project_links(company_id);
create index idx_billing_mail_link_state on billing_mail_project_links(state, last_synced_at);

-- Immutable original handoffs, without a canonical usage_event row or invoice allocation.
-- Remote IDs may duplicate numeric IDs in platform tables: namespace by mail_project_id.
create table billing_mail_usage_imports (
  mail_project_id bigint not null references billing_mail_project_links(mail_project_id)
    on delete restrict,
  remote_usage_id bigint not null,
  company_id bigint not null references companies(id) on delete restrict,
  remote_recipient_id bigint not null,
  remote_message_id bigint not null,
  occurred_at timestamptz not null,
  product_price_micro_inr bigint not null
    check (product_price_micro_inr >= 0),
  imported_at timestamptz not null default now(),
  primary key (mail_project_id, remote_usage_id),
  constraint uk_billing_mail_import_recipient unique (mail_project_id, remote_recipient_id)
);

create index idx_billing_mail_usage_by_company
  on billing_mail_usage_imports (occurred_at, company_id);
create index idx_billing_mail_usage_by_project
  on billing_mail_usage_imports (mail_project_id, occurred_at);
