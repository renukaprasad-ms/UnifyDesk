-- Billing V2: plan-independent, effective-dated default managed-channel prices.
-- Existing company overrides and plan rate cards take priority. This migration does not
-- modify either and does not reprice historical usage event snapshots.
create table billing_global_managed_rates (
    id bigint generated by default as identity primary key,
    billing_sku varchar(64) not null
      check (billing_sku in ('MANAGED_EMAIL_OUTBOUND', 'MANAGED_SMS_SEGMENT')),
    price numeric(19, 6) not null check (price >= 0),
    currency varchar(3) not null default 'INR' check (currency = 'INR'),
    enabled boolean not null default true,
    effective_from timestamptz not null,
    effective_to timestamptz,
    created_by_user_id bigint,
    reason varchar(500),
    created_at timestamptz not null default now(),
    constraint ck_billing_global_rate_range
      check (effective_to is null or effective_to > effective_from),
    constraint uk_billing_global_rate_sku_time unique (billing_sku, effective_from)
);

create index idx_billing_global_rate_lookup
  on billing_global_managed_rates (billing_sku, effective_from desc);

-- A consistent, persisted activation moment per SKU. Historical records cannot be
-- retroactively repriced because financial usage always keeps its resolved price snapshot.
